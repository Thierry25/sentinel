-- Q5
WITH classed_trades AS (
	SELECT 
		CASE
			WHEN PRICE * QTY < 25000 THEN 'SMALL'
			WHEN PRICE * QTY < 60000 THEN 'MEDIUM'
			ELSE 'LARGE'
		END AS trade_class
	FROM TRADE
	WHERE TRADE_TS >= '2026-10-27' AND TRADE_TS < '2026-10-28'

)

SELECT trade_class, COUNT(*) FROM classed_trades
GROUP BY trade_class
ORDER BY 
	CASE trade_class
		WHEN 'SMALL' THEN 1
		WHEN 'MEDIUM' THEN 2
		WHEN 'LARGE' THEN 3
	END;

-- SMALL	2
-- MEDIUM	2
-- LARGE	3