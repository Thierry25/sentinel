]SELECT ACCOUNT_ID,
       (COUNT(CASE WHEN STATUS = 'CANCELLED' THEN 1 END) * 100.0) / NULLIF(COUNT(ORDER_ID), 0) AS cancellation_rate
FROM ORDERS
GROUP BY ACCOUNT_ID 
HAVING COUNT(ORDER_ID) >= 3 
   AND (COUNT(CASE WHEN STATUS = 'CANCELLED' THEN 1 END) * 100.0) / NULLIF(COUNT(ORDER_ID), 0) > 50
ORDER BY cancellation_rate DESC;

