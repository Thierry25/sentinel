SET SCHEMA DRILL;

-- Q1
SELECT ACCOUNT_ID, COUNT(CASE WHEN SIDE = 'B' THEN 1 END) AS number_of_buys,
COUNT(CASE WHEN SIDE = 'S' THEN 1 END) AS number_of_sells,
SUM(CASE WHEN SIDE = 'B' THEN QTY * PRICE END) AS buy_notional,
SUM(CASE WHEN SIDE = 'S' THEN QTY * PRICE ELSE 0 END) AS sell_notional
FROM TRADE
GROUP BY ACCOUNT_ID
ORDER BY ACCOUNT_ID;

