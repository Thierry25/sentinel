-- A400	1	0	26500.0000	0.0000

-- Q2
SELECT d.DESK_ID, 
SUM(CASE WHEN t.SIDE = 'B' THEN t.QTY * t.PRICE ELSE t.QTY * -t.PRICE END) AS net_notional,
SUM(CASE WHEN t.SIDE = 'B' THEN t.QTY * t.PRICE ELSE t.QTY * t.PRICE END) AS gross_notional
FROM DESK d
JOIN ACCOUNT a ON d.DESK_ID = a.DESK_ID
JOIN TRADE t ON t.ACCOUNT_ID = a.ACCOUNT_ID 
WHERE t.TRADE_TS >= '2026-10-27' AND t.TRADE_TS < '2026-10-28'
GROUP BY d.DESK_ID 
ORDER BY gross_notional DESC;

-- Result
-- EQ	-500.0000	210600.0000
-- FI	59190.0000	138310.0000
-- FX	54100.0000	54100.0000

