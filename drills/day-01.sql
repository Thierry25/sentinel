SELECT ACCOUNT_ID, COUNT(*) AS number_of_orders, 
COUNT(CASE WHEN LIMIT_PRICE IS NOT NULL THEN 1 END) AS number_limit_orders,
COUNT(CASE WHEN LIMIT_PRICE IS NULL THEN 1 END) AS number_of_market_orders
FROM ORDERS 
GROUP BY ACCOUNT_ID 
ORDER BY ACCOUNT_ID;

